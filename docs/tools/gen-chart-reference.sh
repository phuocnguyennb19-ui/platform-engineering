#!/usr/bin/env bash
# Generates, from the chart itself (never by hand):
#   docs/reference/application-chart.md               every value of k8s/charts/application
#   docs/schemas/application-values.overlay.schema.json  the chart schema without `required`,
#       so an editor can check a partial values file (values.yaml / <env>/values.yaml of an
#       app) for wrong types, enums and unknown keys without flagging keys that another
#       layer supplies.
# Sources: values.yaml (defaults + the inline comments) and values.schema.json (constraints).
# Usage: make docs-reference   (make docs-check fails when the committed files are stale)
# Needs: yq v4 (mikefarah), jq. Output is deterministic for the same inputs.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT_DIR="${1:-$ROOT/docs}"
CHART="$ROOT/k8s/charts/application"
VALUES="$CHART/values.yaml"
SCHEMA="$CHART/values.schema.json"
MD="$OUT_DIR/reference/application-chart.md"
OVERLAY="$OUT_DIR/schemas/application-values.overlay.schema.json"
mkdir -p "$(dirname "$MD")" "$(dirname "$OVERLAY")"

version="$(yq -r '.version' "$CHART/Chart.yaml")"

# One JSON row per leaf value (scalars, empty maps, lists; list items are not expanded),
# plus the section header (`# ── Title ──`) each top-level key sits under.
rows="$(yq -o=json '
  [ .. | select((tag == "!!map" and length > 0) | not)
       | select(path | length > 0)
       | select(path | map(tag == "!!int") | any | not)
       | {"path": path, "value": ., "comment": (line_comment | sub("^# ?"; ""))} ]' "$VALUES")"
heads="$(yq -o=json 'to_entries | map({"key": .key, "head": (.key | head_comment)})' "$VALUES")"

jq -r --argjson rows "$rows" --argjson heads "$heads" --arg version "$version" '
  . as $schema
  | def esc: tostring | gsub("\\|"; "\\|") | gsub("\n"; " ");
    def deref: if type == "object" and has("$ref")
               then ($schema["$defs"][(.["$ref"] | split("/") | last)] // {}) else . end;
    def node($p): reduce $p[] as $k ($schema; (deref | .properties[$k] // {})) | deref;
    def parent($p): reduce $p[0:-1][] as $k ($schema; (deref | .properties[$k] // {})) | deref;
    def constraint($n):
      [ (if $n.enum then "một trong: " + ($n.enum | map(tostring) | join(", ")) else empty end),
        (if $n.pattern then "pattern `" + $n.pattern + "`" else empty end),
        (if ($n.not.const? // null) != null then "không được là `" + ($n.not.const | tostring) + "`" else empty end),
        (if $n.minimum != null then "≥ " + ($n.minimum | tostring) else empty end),
        (if $n.maximum != null then "≤ " + ($n.maximum | tostring) else empty end),
        (if $n.additionalProperties == false then "chỉ nhận key đã khai báo" else empty end),
        (if $n.description then $n.description else empty end) ] | join("; ");
    def anchor: ascii_downcase | gsub("[^a-z0-9 -]"; "") | gsub(" "; "-");
    def uniq_ordered: reduce .[] as $x ([]; if index([$x]) then . else . + [$x] end);

  # section of each top-level key = the last `── Title ──` header seen so far
  ( reduce $heads[] as $h ({cur: "Chung", map: {}};
      ([ $h.head | split("\n")[] | select(test("── .+ ─")) ] | last) as $t
      | (if $t then .cur = ($t | sub("^#? *── *"; "") | sub(" *─+ *$"; "")) else . end)
      | .map[$h.key] = .cur) | .map ) as $section
  | ([ $heads[].key | $section[.] ] | uniq_ordered) as $sections
  | [ "<!-- GENERATED by docs/tools/gen-chart-reference.sh from k8s/charts/application/{values.yaml,values.schema.json}. Do not edit: run `make docs-reference`. -->",
      "# Tham chiếu value — chart `application` " + $version,
      "",
      "Toàn bộ value mà một app EKS có thể đặt trong `applications/<app>/k8s/values.yaml` và `applications/<app>/k8s/<env>/values.yaml`.",
      "**Mặc định** = giá trị trong `values.yaml` của chart. **Ràng buộc** = `values.schema.json` (render fail nếu vi phạm).",
      "Môi trường đã đặt sẵn gì cho bạn, và thứ tự ghép value: [`../app-onboarding.md`](../app-onboarding.md).",
      "",
      "**Bắt buộc phải có:** `image.repository`, và `image.tag` hoặc `image.digest` (không có fallback `latest`).",
      "Các key gốc `" + ($schema.required | join("`, `")) + "` bắt buộc theo schema nhưng chart đã có mặc định — chỉ ghi đè khi cần.",
      "",
      "Mục: " + ($sections | map("[" + . + "](#" + anchor + ")") | join(" · ")),
      "" ]
    + [ $sections[] as $s
        | ("## " + $s),
          "",
          "| Key | Mặc định | Ghi chú | Ràng buộc |",
          "|---|---|---|---|",
          ( $rows[] | select($section[.path[0]] == $s) | . as $r
            | node(.path) as $n
            | "| `" + (.path | map(tostring) | join(".")) + "`"
              + (if (parent($r.path).required // []) | index([$r.path[-1]]) then " **(bắt buộc)**" else "" end)
              + " | `" + (.value | tojson | esc) + "`"
              + " | " + (.comment | esc)
              + " | " + (constraint($n) | esc) + " |" ),
          "" ]
  | .[]
' "$SCHEMA" > "$MD.tmp"
mv "$MD.tmp" "$MD"

jq 'walk(if type == "object" then del(.required) else . end)
    | .title = "application chart values — partial file (generated: docs/tools/gen-chart-reference.sh)"' \
  "$SCHEMA" > "$OVERLAY.tmp"
mv "$OVERLAY.tmp" "$OVERLAY"

echo "wrote ${MD#$ROOT/} and ${OVERLAY#$ROOT/}"
